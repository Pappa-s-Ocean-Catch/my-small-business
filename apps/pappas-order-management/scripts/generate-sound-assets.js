const fs = require('fs');
const path = require('path');

const soundsDir = path.join(__dirname, '..', 'assets', 'sounds');
const outFile = path.join(__dirname, '..', 'lib', 'sound-assets.generated.ts');

function toLabelFromId(id) {
    return id
        .replace(/[-_]+/g, ' ')
        .replace(/\b\w/g, (c) => c.toUpperCase())
        .trim();
}

function main() {
    if (!fs.existsSync(soundsDir)) {
        console.error('Sounds folder not found:', soundsDir);
        process.exit(1);
    }

    const mp3Files = fs
        .readdirSync(soundsDir)
        .filter((f) => f.toLowerCase().endsWith('.mp3'))
        .sort((a, b) => a.localeCompare(b));

    if (mp3Files.length === 0) {
        console.error('No .mp3 files found in:', soundsDir);
        process.exit(1);
    }

    const soundIds = mp3Files.map((file) => path.basename(file, path.extname(file)));

    const lines = [];
    lines.push('/* eslint-disable */');
    lines.push('// This file is auto-generated by scripts/generate-sound-assets.js');
    lines.push('// Do not edit manually.');
    lines.push('');
    lines.push('export const SOUND_OPTIONS = [');
    for (const id of soundIds) {
        lines.push(`  { id: ${JSON.stringify(id)}, label: ${JSON.stringify(toLabelFromId(id))} },`);
    }
    lines.push('] as const;');
    lines.push('');
    lines.push('export type SoundId = (typeof SOUND_OPTIONS)[number][\'id\'];');
    lines.push('');
    lines.push('export const SOUND_ASSETS: Record<SoundId, any> = {');
    for (const file of mp3Files) {
        const id = path.basename(file, path.extname(file));
        lines.push(`  ${JSON.stringify(id)}: require(${JSON.stringify('../assets/sounds/' + file)}),`);
    }
    lines.push('};');
    lines.push('');

    fs.writeFileSync(outFile, lines.join('\n'), 'utf8');
    console.log(`✓ Generated ${path.relative(process.cwd(), outFile)} (${mp3Files.length} sounds)`);
}

main();
